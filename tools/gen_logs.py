"""Generate src/generated/logs.[ch] from gen_data/logs.yaml.

  tools/gen_logs.py           regenerate the files
  tools/gen_logs.py --check   fail if the committed files differ from the registry
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
YAML = os.path.join(ROOT, "gen_data", "logs.yaml")
OUT_H = os.path.join(ROOT, "src", "generated", "logs.h")
OUT_C = os.path.join(ROOT, "src", "generated", "logs.c")
LEVELS = ("DEBUG", "INFO", "WARN", "ERROR")


def parse(path):
    entries, cur = [], None
    with open(path) as f:
        for n, line in enumerate(f, 1):
            s = line.split("#", 1)[0].rstrip() if not line.lstrip().startswith("text:") else line.rstrip()
            if not s.strip():
                continue
            m = re.match(r'^(-\s+|\s+)(name|level|text):\s*(.*)$', s)
            if not m:
                sys.exit(f"{path}:{n}: cannot parse: {line.rstrip()}")
            key, val = m.group(2), m.group(3).strip().strip('"')
            if m.group(1).startswith("-"):
                cur = {}
                entries.append(cur)
            if cur is None:
                sys.exit(f"{path}:{n}: '{key}' before the first '- name:'")
            cur[key] = val
    names = set()
    for e in entries:
        for k in ("name", "level", "text"):
            if k not in e:
                sys.exit(f"{path}: entry {e} has no '{k}'")
        if not re.match(r"^[A-Z][A-Z0-9_]*$", e["name"]):
            sys.exit(f"{path}: bad name {e['name']!r}")
        if e["level"] not in LEVELS:
            sys.exit(f"{path}: {e['name']}: level must be one of {LEVELS}")
        if e["name"] in names:
            sys.exit(f"{path}: duplicate name {e['name']}")
        names.add(e["name"])
    return entries


def render(entries):
    hdr = "/* Generated by tools/gen_logs.py from gen_data/logs.yaml. Do not edit. */\n"
    h = [hdr, "#ifndef DUMMY_LOGS_H", "#define DUMMY_LOGS_H", "", "typedef enum {"]
    h += [f"    LOG_{e['name']} = {i}," for i, e in enumerate(entries)]
    h += ["    LOG_COUNT", "} log_id_t;", "",
          "typedef struct {", "    const char *name;", "    const char *level;", "    const char *text;", "} log_def_t;", "",
          "extern const log_def_t log_defs[LOG_COUNT];", "", "#endif", ""]
    c = [hdr, '#include "logs.h"', "", "const log_def_t log_defs[LOG_COUNT] = {"]
    c += [f'    [LOG_{e["name"]}] = {{"{e["name"]}", "{e["level"]}", "{e["text"]}"}},' for e in entries]
    c += ["};", ""]
    return "\n".join(h), "\n".join(c)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    h, c = render(parse(YAML))
    if args.check:
        bad = [p for p, t in ((OUT_H, h), (OUT_C, c)) if not os.path.exists(p) or open(p).read() != t]
        if bad:
            sys.exit("generated files are out of date, run tools/gen_logs.py: " + ", ".join(os.path.relpath(p, ROOT) for p in bad))
        print("generated files match gen_data/logs.yaml")
        return
    os.makedirs(os.path.dirname(OUT_H), exist_ok=True)
    for p, t in ((OUT_H, h), (OUT_C, c)):
        with open(p, "w") as f:
            f.write(t)
    print("wrote", os.path.relpath(OUT_H, ROOT), os.path.relpath(OUT_C, ROOT))


if __name__ == "__main__":
    main()
